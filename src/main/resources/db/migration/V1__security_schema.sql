-- =====================================================================
-- V1: esquema de seguridad (usuarios, roles, permisos, refresh tokens)
-- Replica el modelo de ticket-backend (schema "security") sin LDAP.
-- =====================================================================
CREATE SCHEMA IF NOT EXISTS security;

CREATE TABLE security.user_app (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(50)  NOT NULL,
    full_name   VARCHAR(150) NOT NULL,
    email       VARCHAR(150),
    password    VARCHAR(100) NOT NULL,
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_by  VARCHAR(150),
    updated_by  VARCHAR(150),
    created_at  TIMESTAMP,
    updated_at  TIMESTAMP
);
CREATE UNIQUE INDEX ux_user_app_username ON security.user_app (lower(username));
CREATE UNIQUE INDEX ux_user_app_email ON security.user_app (lower(email)) WHERE email IS NOT NULL;

CREATE TABLE security.role (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    code        VARCHAR(15)  NOT NULL,
    description VARCHAR(255),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_by  VARCHAR(150),
    updated_by  VARCHAR(150),
    created_at  TIMESTAMP,
    updated_at  TIMESTAMP,
    CONSTRAINT ux_role_name UNIQUE (name),
    CONSTRAINT ux_role_code UNIQUE (code)
);

CREATE TABLE security.permission (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255),
    description     VARCHAR(255),
    http_method     VARCHAR(10)  NOT NULL,
    url             VARCHAR(255) NOT NULL,
    url_without_ids VARCHAR(255) NOT NULL,
    code            VARCHAR(255) NOT NULL,
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    created_by      VARCHAR(150),
    updated_by      VARCHAR(150),
    created_at      TIMESTAMP,
    updated_at      TIMESTAMP,
    CONSTRAINT ux_permission_code UNIQUE (code)
);
CREATE INDEX ix_permission_method_url ON security.permission (http_method, url_without_ids);

CREATE TABLE security.user_role (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    role_id INTEGER NOT NULL,
    CONSTRAINT ux_user_role UNIQUE (user_id, role_id),
    CONSTRAINT fk_user_role_user_app FOREIGN KEY (user_id) REFERENCES security.user_app (id) ON DELETE RESTRICT,
    CONSTRAINT fk_user_role_role FOREIGN KEY (role_id) REFERENCES security.role (id) ON DELETE RESTRICT
);

CREATE TABLE security.role_permission (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id       INTEGER NOT NULL,
    permission_id INTEGER NOT NULL,
    CONSTRAINT ux_role_permission UNIQUE (role_id, permission_id),
    CONSTRAINT fk_role_permission_role FOREIGN KEY (role_id) REFERENCES security.role (id) ON DELETE RESTRICT,
    CONSTRAINT fk_role_permission_permission FOREIGN KEY (permission_id) REFERENCES security.permission (id) ON DELETE RESTRICT
);

CREATE TABLE security.refresh_token (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(50)  NOT NULL,
    token_hash  VARCHAR(100) NOT NULL,
    expires_at  TIMESTAMP    NOT NULL,
    revoked     BOOLEAN      NOT NULL DEFAULT FALSE,
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_by  VARCHAR(150),
    updated_by  VARCHAR(150),
    created_at  TIMESTAMP,
    updated_at  TIMESTAMP,
    CONSTRAINT ux_refresh_token_hash UNIQUE (token_hash)
);
CREATE INDEX ix_refresh_token_username ON security.refresh_token (username) WHERE revoked = FALSE;
