-- =====================================================================
-- V3: catálogo (Etapa 2) — categorías, productos, adicionales, adornos
-- numerados, medios de pago y parámetros del sistema.
-- Borrado lógico (active=false) en todas las tablas: el histórico de
-- pedidos referenciará estas filas.
-- =====================================================================

CREATE TABLE categories (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    description   VARCHAR(500),
    image_base64  TEXT,
    ranking       INTEGER      NOT NULL DEFAULT 0,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_by    VARCHAR(150),
    updated_by    VARCHAR(150),
    created_at    TIMESTAMP,
    updated_at    TIMESTAMP
);
CREATE UNIQUE INDEX ux_categories_name ON categories (lower(name)) WHERE active;

CREATE TABLE products (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id   INTEGER       NOT NULL,
    name          VARCHAR(100)  NOT NULL,
    description   VARCHAR(500),
    image_base64  TEXT,
    price         NUMERIC(12,2) NOT NULL,
    available     BOOLEAN       NOT NULL DEFAULT TRUE,
    version       BIGINT        NOT NULL DEFAULT 0,
    active        BOOLEAN       NOT NULL DEFAULT TRUE,
    created_by    VARCHAR(150),
    updated_by    VARCHAR(150),
    created_at    TIMESTAMP,
    updated_at    TIMESTAMP,
    CONSTRAINT fk_products_categories FOREIGN KEY (category_id) REFERENCES categories (id) ON DELETE RESTRICT,
    CONSTRAINT ck_products_price_non_negative CHECK (price >= 0)
);
CREATE UNIQUE INDEX ux_products_name ON products (lower(name)) WHERE active;
CREATE INDEX ix_products_category_id ON products (category_id);

CREATE TABLE addons (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)  NOT NULL,
    price       NUMERIC(12,2) NOT NULL,
    active      BOOLEAN       NOT NULL DEFAULT TRUE,
    created_by  VARCHAR(150),
    updated_by  VARCHAR(150),
    created_at  TIMESTAMP,
    updated_at  TIMESTAMP,
    CONSTRAINT ck_addons_price_non_negative CHECK (price >= 0)
);
CREATE UNIQUE INDEX ux_addons_name ON addons (lower(name)) WHERE active;

-- Tabla puente N:M (sin historia: borrado físico permitido)
CREATE TABLE product_addons (
    product_id  INTEGER NOT NULL,
    addon_id    INTEGER NOT NULL,
    CONSTRAINT pk_product_addons PRIMARY KEY (product_id, addon_id),
    CONSTRAINT fk_product_addons_products FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT,
    CONSTRAINT fk_product_addons_addons FOREIGN KEY (addon_id) REFERENCES addons (id) ON DELETE RESTRICT
);
CREATE INDEX ix_product_addons_addon_id ON product_addons (addon_id);

-- Adornos numerados que el cajero entrega al cliente para ponerlos en su mesa
CREATE TABLE table_markers (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number       INTEGER      NOT NULL,
    description  VARCHAR(255),
    active       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_by   VARCHAR(150),
    updated_by   VARCHAR(150),
    created_at   TIMESTAMP,
    updated_at   TIMESTAMP,
    CONSTRAINT ck_table_markers_number_positive CHECK (number > 0)
);
CREATE UNIQUE INDEX ux_table_markers_number ON table_markers (number) WHERE active;

CREATE TABLE payment_methods (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR(30)  NOT NULL,
    name                VARCHAR(100) NOT NULL,
    requires_reference  BOOLEAN      NOT NULL DEFAULT FALSE,
    gives_change        BOOLEAN      NOT NULL DEFAULT FALSE,
    active              BOOLEAN      NOT NULL DEFAULT TRUE,
    created_by          VARCHAR(150),
    updated_by          VARCHAR(150),
    created_at          TIMESTAMP,
    updated_at          TIMESTAMP,
    CONSTRAINT ux_payment_methods_code UNIQUE (code)
);

-- Parámetros del sistema (patrón Parameter de la referencia + code/value_type para valores de configuración)
CREATE TABLE parameters (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folder       VARCHAR(30)  NOT NULL,
    code         VARCHAR(60)  NOT NULL,
    name         VARCHAR(150) NOT NULL,
    value        VARCHAR(255) NOT NULL,
    value_type   VARCHAR(20)  NOT NULL,
    description  VARCHAR(500),
    editable     BOOLEAN      NOT NULL DEFAULT TRUE,
    active       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_by   VARCHAR(150),
    updated_by   VARCHAR(150),
    created_at   TIMESTAMP,
    updated_at   TIMESTAMP,
    CONSTRAINT ux_parameters_code UNIQUE (code),
    CONSTRAINT ck_parameters_folder CHECK (folder IN ('SYSTEM', 'DISCOUNTS')),
    CONSTRAINT ck_parameters_value_type CHECK (value_type IN ('PERCENTAGE', 'NUMBER', 'TEXT', 'BOOLEAN'))
);

