-- =====================================================================
-- V5: caja (apertura y movimientos), pedidos, detalle con fotografías de
-- precio, historial de estados y pagos (Etapa 3).
-- Nada de estas tablas se borra físicamente (skill cdr-order-management §13).
-- Estados y tipos se guardan con el name() del enum Java (inglés).
-- =====================================================================

-- ----- Caja: una sesión OPEN por usuario -----
CREATE TABLE cash_sessions (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         INTEGER       NOT NULL,
    status          VARCHAR(10)   NOT NULL,
    opening_amount  NUMERIC(12,2) NOT NULL,
    opened_at       TIMESTAMP     NOT NULL,
    closed_at       TIMESTAMP,
    closing_note    VARCHAR(500),
    version         BIGINT        NOT NULL DEFAULT 0,
    active          BOOLEAN       NOT NULL DEFAULT TRUE,
    created_by      VARCHAR(150),
    updated_by      VARCHAR(150),
    created_at      TIMESTAMP,
    updated_at      TIMESTAMP,
    CONSTRAINT fk_cash_sessions_user_app FOREIGN KEY (user_id) REFERENCES security.user_app (id) ON DELETE RESTRICT,
    CONSTRAINT ck_cash_sessions_status CHECK (status IN ('OPEN', 'CLOSED')),
    CONSTRAINT ck_cash_sessions_opening_non_negative CHECK (opening_amount >= 0)
);
CREATE UNIQUE INDEX ux_cash_sessions_user_open ON cash_sessions (user_id) WHERE status = 'OPEN';

-- ----- Correlativo diario del código visible del pedido (#001 reinicia cada día, America/La_Paz) -----
CREATE TABLE order_daily_sequences (
    business_date  DATE    PRIMARY KEY,
    last_value     INTEGER NOT NULL
);

-- ----- Pedidos -----
CREATE TABLE orders (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_date        DATE          NOT NULL,
    code                 INTEGER       NOT NULL,
    service_type         VARCHAR(10)   NOT NULL,
    table_marker_id      INTEGER,
    table_marker_number  INTEGER,
    customer_name        VARCHAR(100),
    status               VARCHAR(20)   NOT NULL,
    subtotal             NUMERIC(12,2) NOT NULL,
    discount_type        VARCHAR(15),
    discount_value       NUMERIC(12,2),
    discount_amount      NUMERIC(12,2) NOT NULL DEFAULT 0,
    total                NUMERIC(12,2) NOT NULL,
    discount_reason      VARCHAR(255),
    discount_applied_by  VARCHAR(150),
    discount_applied_at  TIMESTAMP,
    cancel_reason        VARCHAR(255),
    cancelled_by         VARCHAR(150),
    cancelled_at         TIMESTAMP,
    cash_session_id      INTEGER       NOT NULL,
    version              BIGINT        NOT NULL DEFAULT 0,
    active               BOOLEAN       NOT NULL DEFAULT TRUE,
    created_by           VARCHAR(150),
    updated_by           VARCHAR(150),
    created_at           TIMESTAMP,
    updated_at           TIMESTAMP,
    CONSTRAINT fk_orders_table_markers FOREIGN KEY (table_marker_id) REFERENCES table_markers (id) ON DELETE RESTRICT,
    CONSTRAINT fk_orders_cash_sessions FOREIGN KEY (cash_session_id) REFERENCES cash_sessions (id) ON DELETE RESTRICT,
    CONSTRAINT ux_orders_business_date_code UNIQUE (business_date, code),
    CONSTRAINT ck_orders_service_type CHECK (service_type IN ('DINE_IN', 'TAKEAWAY')),
    CONSTRAINT ck_orders_status CHECK (status IN ('PENDING', 'IN_PREPARATION', 'READY', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT ck_orders_discount_type CHECK (discount_type IS NULL OR discount_type IN ('PERCENTAGE', 'FIXED_AMOUNT')),
    CONSTRAINT ck_orders_marker_by_service CHECK (
        (service_type = 'DINE_IN'  AND table_marker_id IS NOT NULL AND table_marker_number IS NOT NULL) OR
        (service_type = 'TAKEAWAY' AND table_marker_id IS NULL AND table_marker_number IS NULL)),
    CONSTRAINT ck_orders_amounts CHECK (subtotal >= 0 AND discount_amount >= 0
        AND discount_amount <= subtotal AND total = subtotal - discount_amount)
);
-- Un adorno solo puede tener un pedido abierto: protege contra dos cajeros que lo asignan a la vez
CREATE UNIQUE INDEX ux_orders_marker_open ON orders (table_marker_id)
    WHERE status IN ('PENDING', 'IN_PREPARATION', 'READY');
CREATE INDEX ix_orders_status ON orders (status);
CREATE INDEX ix_orders_cash_session_id ON orders (cash_session_id);
CREATE INDEX ix_orders_created_at ON orders (created_at);

-- ----- Detalle: fotografías de precio y nombres -----
CREATE TABLE order_items (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id           INTEGER       NOT NULL,
    product_id         INTEGER       NOT NULL,
    product_name       VARCHAR(100)  NOT NULL,
    category_id        INTEGER       NOT NULL,
    category_name      VARCHAR(100)  NOT NULL,
    quantity           INTEGER       NOT NULL,
    unit_price         NUMERIC(12,2) NOT NULL,
    addons_unit_total  NUMERIC(12,2) NOT NULL DEFAULT 0,
    line_subtotal      NUMERIC(12,2) NOT NULL,
    notes              VARCHAR(255),
    CONSTRAINT fk_order_items_orders FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT,
    CONSTRAINT fk_order_items_products FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT,
    CONSTRAINT fk_order_items_categories FOREIGN KEY (category_id) REFERENCES categories (id) ON DELETE RESTRICT,
    CONSTRAINT ck_order_items_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_order_items_amounts CHECK (unit_price >= 0 AND addons_unit_total >= 0 AND line_subtotal >= 0)
);
CREATE INDEX ix_order_items_order_id ON order_items (order_id);
CREATE INDEX ix_order_items_product_id ON order_items (product_id);

CREATE TABLE order_item_addons (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id  INTEGER       NOT NULL,
    addon_id       INTEGER       NOT NULL,
    addon_name     VARCHAR(100)  NOT NULL,
    unit_price     NUMERIC(12,2) NOT NULL,
    CONSTRAINT fk_order_item_addons_order_items FOREIGN KEY (order_item_id) REFERENCES order_items (id) ON DELETE RESTRICT,
    CONSTRAINT fk_order_item_addons_addons FOREIGN KEY (addon_id) REFERENCES addons (id) ON DELETE RESTRICT,
    CONSTRAINT ck_order_item_addons_price CHECK (unit_price >= 0)
);
CREATE INDEX ix_order_item_addons_order_item_id ON order_item_addons (order_item_id);

CREATE TABLE order_status_history (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     INTEGER      NOT NULL,
    from_status  VARCHAR(20),
    to_status    VARCHAR(20)  NOT NULL,
    changed_by   VARCHAR(150) NOT NULL,
    changed_at   TIMESTAMP    NOT NULL,
    note         VARCHAR(255),
    CONSTRAINT fk_order_status_history_orders FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT
);
CREATE INDEX ix_order_status_history_order_id ON order_status_history (order_id);

-- ----- Pagos (importe aplicado; NO se guarda recibido ni vuelto) -----
CREATE TABLE payments (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id           INTEGER       NOT NULL,
    cash_session_id    INTEGER       NOT NULL,
    payment_method_id  INTEGER       NOT NULL,
    amount             NUMERIC(12,2) NOT NULL,
    reference          VARCHAR(100),
    status             VARCHAR(10)   NOT NULL,
    active             BOOLEAN       NOT NULL DEFAULT TRUE,
    created_by         VARCHAR(150),
    updated_by         VARCHAR(150),
    created_at         TIMESTAMP,
    updated_at         TIMESTAMP,
    CONSTRAINT fk_payments_orders FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT,
    CONSTRAINT fk_payments_cash_sessions FOREIGN KEY (cash_session_id) REFERENCES cash_sessions (id) ON DELETE RESTRICT,
    CONSTRAINT fk_payments_payment_methods FOREIGN KEY (payment_method_id) REFERENCES payment_methods (id) ON DELETE RESTRICT,
    CONSTRAINT ck_payments_amount_positive CHECK (amount > 0),
    CONSTRAINT ck_payments_status CHECK (status IN ('PAID', 'REFUNDED'))
);
CREATE INDEX ix_payments_order_id ON payments (order_id);
CREATE INDEX ix_payments_cash_session_id ON payments (cash_session_id);

-- ----- Bitácora de caja (inmutable) -----
-- payment_method_id solo en SALE/REFUND; OPENING/INCOME/EXPENSE son efectivo.
CREATE TABLE cash_movements (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cash_session_id    INTEGER       NOT NULL,
    type               VARCHAR(10)   NOT NULL,
    payment_method_id  INTEGER,
    amount             NUMERIC(12,2) NOT NULL,
    order_id           INTEGER,
    payment_id         INTEGER,
    description        VARCHAR(255),
    active             BOOLEAN       NOT NULL DEFAULT TRUE,
    created_by         VARCHAR(150),
    updated_by         VARCHAR(150),
    created_at         TIMESTAMP,
    updated_at         TIMESTAMP,
    CONSTRAINT fk_cash_movements_cash_sessions FOREIGN KEY (cash_session_id) REFERENCES cash_sessions (id) ON DELETE RESTRICT,
    CONSTRAINT fk_cash_movements_payment_methods FOREIGN KEY (payment_method_id) REFERENCES payment_methods (id) ON DELETE RESTRICT,
    CONSTRAINT fk_cash_movements_orders FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT,
    CONSTRAINT fk_cash_movements_payments FOREIGN KEY (payment_id) REFERENCES payments (id) ON DELETE RESTRICT,
    CONSTRAINT ck_cash_movements_type CHECK (type IN ('OPENING', 'SALE', 'REFUND', 'INCOME', 'EXPENSE')),
    CONSTRAINT ck_cash_movements_amount CHECK (amount >= 0),
    CONSTRAINT ck_cash_movements_sale_method CHECK (type NOT IN ('SALE', 'REFUND') OR payment_method_id IS NOT NULL)
);
CREATE INDEX ix_cash_movements_cash_session_id ON cash_movements (cash_session_id);

