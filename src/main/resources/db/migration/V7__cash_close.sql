-- =====================================================================

ALTER TABLE cash_sessions ADD COLUMN closed_by VARCHAR(150);

CREATE TABLE cash_session_summaries (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cash_session_id    INTEGER       NOT NULL,
    payment_method_id  INTEGER       NOT NULL,
    expected_amount    NUMERIC(12,2) NOT NULL,
    declared_amount    NUMERIC(12,2) NOT NULL,
    difference         NUMERIC(12,2) NOT NULL,
    active             BOOLEAN       NOT NULL DEFAULT TRUE,
    created_by         VARCHAR(150),
    updated_by         VARCHAR(150),
    created_at         TIMESTAMP,
    updated_at         TIMESTAMP,
    CONSTRAINT fk_cash_session_summaries_cash_sessions FOREIGN KEY (cash_session_id) REFERENCES cash_sessions (id) ON DELETE RESTRICT,
    CONSTRAINT fk_cash_session_summaries_payment_methods FOREIGN KEY (payment_method_id) REFERENCES payment_methods (id) ON DELETE RESTRICT,
    CONSTRAINT ux_cash_session_summaries_method UNIQUE (cash_session_id, payment_method_id),
    CONSTRAINT ck_cash_session_summaries_declared CHECK (declared_amount >= 0),
    CONSTRAINT ck_cash_session_summaries_difference CHECK (difference = declared_amount - expected_amount)
);

CREATE INDEX ix_cash_sessions_opened_at ON cash_sessions (opened_at);

